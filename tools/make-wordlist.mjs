// Builds packages/core/src/wordlist.ts from the BIP-39 English list, minus words
// that don't belong in a family app. Run once; the output is FROZEN: changing it
// would change everyone's keys. test/wordlist.test.ts checks its hash.
//
//   node tools/make-wordlist.mjs
import { wordlist } from '@scure/bip39/wordlists/english.js';
import { writeFileSync } from 'node:fs';

const deny = new Set(`
abuse addict alcohol alien angry arrest attack blame blood bomb bullet cage cancel
casino chaos cigar clog coffin corpse crash crime cruel crush curse danger dash debt
deny depend despair destroy devil disease dismiss divorce drastic drug drunk dumb
enemy erase error evil evoke exile expire fatal fault fever fiction foil fragile
frown gun guilt harsh hazard hip hurt idiot ignore ill illegal illness inflict injury
insane insult jail junk kill lawsuit liar lonely lunatic mad naked nasty negative
neglect nerve nuclear obscure oppose orphan pain panic penalty pistol poison poverty
prison problem punch radar rage reject resist rifle risk rude sad scare scatter
scheme sick siege sin skull slam slap slaughter sniff sorry spoil spy stab stupid
suicide suspect swear sword tank tattoo terror threat toxic tragic trap trash trick
trouble ugly unfair unhappy upset vague violent virus vote war warfare weapon weird
wicked worry wreck wrong
`.split(/\s+/).filter(Boolean));

const words = wordlist.filter(w => !deny.has(w));
const body = `// GENERATED by tools/make-wordlist.mjs from the BIP-39 English list. FROZEN: do not edit.
// ${words.length} words. Changing this list changes everyone's keys.
export const WORDS: readonly string[] = Object.freeze(${JSON.stringify(words)});
`;
writeFileSync(new URL('../packages/core/src/wordlist.ts', import.meta.url), body);
console.log(`${words.length} words (removed ${wordlist.length - words.length})`);
